import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const RAW_VAULT_PATH = path.join(ROOT, 'vault-raw', 'secrets.json');
const OUT_TS_PATH = path.join(ROOT, 'src', 'data', 'encryptedVault.ts');

function normalizePassphrase(raw) {
  return String(raw).trim().toLowerCase().replace(/[\s\-_—·:：]/g, '');
}

function sha256Hex(input) {
  return crypto.createHash('sha256').update(normalizePassphrase(input), 'utf8').digest('hex');
}

function encryptText(plaintext, passphrase) {
  const norm = normalizePassphrase(passphrase);
  const salt = crypto.randomBytes(16);
  const iv = crypto.randomBytes(12);
  const key = crypto.pbkdf2Sync(Buffer.from(norm, 'utf8'), salt, 25000, 32, 'sha256');

  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const encrypted = Buffer.concat([cipher.update(plaintext, 'utf8'), cipher.final()]);
  const authTag = cipher.getAuthTag();
  const combined = Buffer.concat([encrypted, authTag]);

  return {
    iv: iv.toString('base64'),
    salt: salt.toString('base64'),
    ciphertext: combined.toString('base64'),
    keyHintHash: sha256Hex('qinghe_salt_98::' + norm),
  };
}

function main() {
  if (!fs.existsSync(RAW_VAULT_PATH)) {
    if (fs.existsSync(OUT_TS_PATH)) {
      console.log('[encrypt-content] vault-raw/secrets.json not present; using pre-built src/data/encryptedVault.ts.');
      return;
    }
    console.error('[encrypt-content] Missing both vault-raw/secrets.json and src/data/encryptedVault.ts!');
    process.exit(1);
  }

  const raw = JSON.parse(fs.readFileSync(RAW_VAULT_PATH, 'utf8'));
  const vaultBlocks = {};
  const passHashes = {};

  for (const [id, entry] of Object.entries(raw.blocks)) {
    vaultBlocks[id] = encryptText(
      typeof entry.payload === 'string' ? entry.payload : JSON.stringify(entry.payload),
      entry.key
    );
  }

  for (const [gateId, pass] of Object.entries(raw.gates)) {
    passHashes[gateId] = sha256Hex('qinghe_salt_98::' + normalizePassphrase(pass));
  }

  fs.mkdirSync(path.dirname(OUT_TS_PATH), { recursive: true });
  const fileBanner = `// AUTO-GENERATED BY scripts/encrypt-content.mjs — DO NOT EDIT DIRECTLY.
// All late-game documents, private notes, and multi-ending payloads are AES-256-GCM encrypted
// with PBKDF2-SHA256 derived puzzle keys so static GitHub Pages bundles do not leak spoilers.

import type { EncryptedBlock } from '../types/game';

export const GATE_HASHES: Record<string, string> = ${JSON.stringify(passHashes, null, 2)};

export const ENCRYPTED_VAULT: Record<string, EncryptedBlock> = ${JSON.stringify(vaultBlocks, null, 2)};
`;

  fs.writeFileSync(OUT_TS_PATH, fileBanner, 'utf8');
  console.log(
    `[encrypt-content] Encrypted ${Object.keys(vaultBlocks).length} secret blocks and ${Object.keys(passHashes).length} security gates -> src/data/encryptedVault.ts`
  );
}

main();
